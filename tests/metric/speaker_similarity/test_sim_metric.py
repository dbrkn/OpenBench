"""Tests for the Speaker Similarity (SIM) metric.

Fully self-contained: no model download, no audio (.wav) files, and no .npz
fixture. The reliability test hardcodes the WavLM-large speaker embeddings of
the Trump voice-cloning clips and the SIM values BytedanceSpeech/seed-tts-eval
produced for them, then checks that our cosine/aggregation logic reproduces
those numbers within a small error margin.
"""

