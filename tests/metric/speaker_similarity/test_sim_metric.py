def test_trump_sim_matches_bytedance_within_tolerance(monkeypatch):
    """Our SIM on the hardcoded Trump embeddings reproduces ByteDance's seed-tts-eval SIM."""
    embeddings = {key: torch.tensor([vec], dtype=torch.float32) for key, vec in _TRUMP_EMBEDDINGS.items()}

    metric = SpeakerSimilarity(checkpoint=None)
    monkeypatch.setattr(metric, "_embed", lambda key: embeddings[key])

    for name, (generated, reference) in _TRUMP_PAIRS.items():
        sim = metric(generated, reference, uri=name)
        expected = BYTEDANCE_SIM[name]
        assert sim == pytest.approx(expected, rel=SIM_TOLERANCE), (
            f"{name}: our SIM {sim:.4f} differs from ByteDance {expected} "
            f"by more than {SIM_TOLERANCE:.0%}"
        )

    assert abs(metric) == pytest.approx(np.mean(list(BYTEDANCE_SIM.values())), rel=SIM_TOLERANCE)
